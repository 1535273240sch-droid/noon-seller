#!/bin/sh
set -eu
psql --set=ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=app_pass="$APP_DB_PASSWORD" --set=migrate_pass="$MIGRATE_DB_PASSWORD" <<'SQL'
CREATE ROLE noon_app LOGIN PASSWORD :'app_pass' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE noon_migrate LOGIN PASSWORD :'migrate_pass' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE,CREATE ON SCHEMA public TO noon_migrate;
GRANT USAGE ON SCHEMA public TO noon_app;
SQL
